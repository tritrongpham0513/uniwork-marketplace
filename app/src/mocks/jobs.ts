const cat = (slug: string) =>
  JOB_CATEGORIES.find((c) => c.slug === slug) ?? JOB_CATEGORIES[0];

const emp = (id: string) => EMPLOYERS.find((e) => e.id === id) ?? EMPLOYERS[0];

const skill = (name: string) => ({ id: name.toLowerCase().replaceAll(" ", "-"), name });

const schedule = (
  dayOfWeek: DayOfWeek,
  startTime: string,
  endTime: string,
): JobSchedule => ({ dayOfWeek, startTime, endTime });

/** Ngày đăng giảm dần từ hôm nay (giờ đã trôi) */
const hoursAgo = (h: number) =>
  new Date(Date.now() - h * 3600 * 1000).toISOString();

const daysFromNow = (d: number) =>
  new Date(Date.now() + d * 86400 * 1000).toISOString();

/** Tìm quận theo tên + tỉnh, fallback về quận đầu tiên của tỉnh */
const dist = (provinceId: string, name: string) =>
  DISTRICTS.find((d) => d.provinceId === provinceId && d.name === name) ??
  DISTRICTS.find((d) => d.provinceId === provinceId);

